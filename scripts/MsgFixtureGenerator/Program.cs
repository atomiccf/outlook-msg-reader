using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using MsgKit;

if (args.Length != 1)
{
    Console.Error.WriteLine("Usage: MsgFixtureGenerator <output-directory>");
    return 2;
}

var outputRoot = Path.GetFullPath(args[0]);
var assetsRoot = Path.Combine(outputRoot, "_assets");
Directory.CreateDirectory(outputRoot);
Directory.CreateDirectory(assetsRoot);

var smallAttachment = Path.Combine(assetsRoot, "unicode-text.txt");
var largeAttachment = Path.Combine(assetsRoot, "large-binary.bin");
File.WriteAllText(
    smallAttachment,
    "Zażółć gęślą jaźń\r\nПривет, мир\r\nEmoji: 😀",
    new UTF8Encoding(false));
File.WriteAllBytes(largeAttachment, Enumerable.Range(0, 8192).Select(i => (byte)(i % 251)).ToArray());

var fixtures = new List<object>();

fixtures.Add(SaveMessage(
    "plain-basic-unicode",
    "Basic plain message",
    bodyText: "Simple message body.",
    to: new[] { ("recipient@example.test", "Recipient") },
    expected: new { subject = "Basic plain message", textContains = "Simple message body." }));

fixtures.Add(SaveMessage(
    "unicode-polish-russian",
    "Zażółć gęślą jaźń — Тестовое письмо",
    bodyText: "Polski: Zażółć gęślą jaźń.\r\nРусский: Привет, мир.\r\nEmoji: 😀",
    to: new[] { ("jan@example.test", "Jan Kowalski") },
    cc: new[] { ("ivan@example.test", "Иван Иванов") },
    bcc: new[] { ("hidden@example.test", "Hidden Recipient") },
    expected: new
    {
        subject = "Zażółć gęślą jaźń — Тестовое письмо",
        toCount = 1,
        ccCount = 1,
        bccCount = 1
    }));

fixtures.Add(SaveMessage(
    "html-unicode",
    "HTML message",
    bodyText: "HTML test: Polski, русский и emoji 😀",
    bodyHtml: "<html><body><h1>HTML test</h1><p>Polski, русский и emoji 😀</p></body></html>",
    expected: new { subject = "HTML message", htmlContains = "<h1>HTML test</h1>" }));

fixtures.Add(SaveMessage(
    "rtf-unicode",
    "RTF message",
    bodyText: "RTF body generated by MsgKit.",
    bodyRtf: @"{\rtf1\ansi\deff0 RTF body generated by MsgKit.}",
    expected: new { subject = "RTF message", rtfPresent = true }));

fixtures.Add(SaveMessage(
    "empty-unicode",
    string.Empty,
    expected: new { subject = string.Empty, attachmentCount = 0 }));

fixtures.Add(SaveMessage(
    "small-attachment",
    "Small attachment",
    bodyText: "Contains a small attachment.",
    attachments: new[] { smallAttachment },
    expected: new
    {
        subject = "Small attachment",
        attachmentCount = 1,
        attachmentNames = new[] { "unicode-text.txt" }
    }));

fixtures.Add(SaveMessage(
    "large-attachment",
    "Large attachment",
    bodyText: "Contains an attachment larger than 4096 bytes.",
    attachments: new[] { largeAttachment },
    expected: new
    {
        subject = "Large attachment",
        attachmentCount = 1,
        attachmentNames = new[] { "large-binary.bin" }
    }));

fixtures.Add(SaveMessage(
    "multiple-attachments",
    "Multiple attachments",
    bodyText: "Two attachments",
    bodyHtml: "<html><body>Two attachments</body></html>",
    attachments: new[] { smallAttachment, largeAttachment },
    expected: new { subject = "Multiple attachments", attachmentCount = 2 }));

var manifest = new
{
    schemaVersion = 1,
    generator = "scripts/MsgFixtureGenerator",
    producer = "MsgKit 3.0.5",
    limitations = new[]
    {
        "ANSI MSG and true embedded-message fixtures require Microsoft Outlook classic."
    },
    fixtures
};

var manifestPath = Path.Combine(outputRoot, "manifest.json");
File.WriteAllText(
    manifestPath,
    JsonSerializer.Serialize(manifest, new JsonSerializerOptions { WriteIndented = true }),
    new UTF8Encoding(false));

Console.WriteLine($"Generated {fixtures.Count} MSG fixtures with MsgKit in {outputRoot}");
return 0;

object SaveMessage(
    string id,
    string subject,
    string bodyText = "",
    string? bodyHtml = null,
    string? bodyRtf = null,
    (string Address, string Name)[]? to = null,
    (string Address, string Name)[]? cc = null,
    (string Address, string Name)[]? bcc = null,
    string[]? attachments = null,
    object? expected = null)
{
    var target = Path.Combine(outputRoot, id + ".msg");
    if (File.Exists(target))
        File.Delete(target);

    using (var email = new Email(new Sender("sender@example.test", "Fixture Sender"), subject))
    {
        email.BodyText = bodyText;
        email.BodyHtml = bodyHtml;
        if (bodyRtf is not null)
        {
            email.BodyRtf = bodyRtf;
            email.BodyRtfCompressed = false;
        }

        foreach (var recipient in to ?? Array.Empty<(string, string)>())
            email.Recipients.AddTo(recipient.Address, recipient.Name);
        foreach (var recipient in cc ?? Array.Empty<(string, string)>())
            email.Recipients.AddCc(recipient.Address, recipient.Name);
        foreach (var recipient in bcc ?? Array.Empty<(string, string)>())
            email.Recipients.AddBcc(recipient.Address, recipient.Name);
        foreach (var attachment in attachments ?? Array.Empty<string>())
            email.Attachments.Add(attachment);

        email.Save(target);
    }

    return new
    {
        id,
        file = Path.GetFileName(target),
        producer = "MsgKit 3.0.5",
        msgFormat = "unicode",
        bodyFormat = bodyRtf is not null ? "rtf" : bodyHtml is not null ? "html" : "plain",
        sha256 = Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(target))).ToLowerInvariant(),
        expected = expected ?? new { }
    };
}
